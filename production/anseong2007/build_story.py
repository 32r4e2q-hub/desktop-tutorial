def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def cjk_count(text: str) -> int:
    """Spoken-length proxy: CJK chars + digits read aloud (each digit ≈ one syllable)."""
    return len(re.findall(r"[\u4e00-\u9fff]", text)) + len(re.findall(r"\d", text))


