def build() -> dict:
    ledger = HERE / "reference" / "approvals.json"
    approvals = json.loads(ledger.read_text(encoding="utf-8")).get("assets", {}) if ledger.is_file() else {}
    shots, cursor = [], 0
    for index, (sid, dur, ref_text, role_text, narr, tts, camera, sfx, visual, hl) in enumerate(ROWS):
        refs = ref_text.split(",")
        roles = [r for r in role_text.split(";") if r]
        anchors = "；".join(CHARACTERS[r] for r in roles)
        notes = "【参考图说明】" + "；".join(
            f"图{n}为{rid}（{REF_DESC[rid]}），仅作人物身份、服装、场景结构或道具外观参考；不要复制设定板/拼贴排版，不要生成任何文字"
            for n, rid in enumerate(refs, 1))
        parts = [STYLE] + ([anchors] if anchors else []) + [f"{visual} 运镜：{camera}。", notes, NEGATIVE]
        for key in hl:
            assert key in narr, (sid, key)
        shots.append({
            "id": sid, "start": cursor, "duration": dur, "seconds": dur, "kind": "agnes",
            "reference_images": refs, "character_anchors": roles,
            "narration": narr, "tts_text": tts, "narration_id": sid, "subtitle": narr,
            "camera": camera, "sfx": sfx, "visual_prompt": visual,
            "prompt": "\n".join(parts), "highlight_keywords": hl, "seed": 1997000 + index,
        })
        cursor += dur
    assert cursor == 180 and len(shots) == 30
    refs_all = list(REF_DESC)
    story = {
        "title": TITLE, "slug": SLUG, "target_duration": 180, "aspect": "16:9",
        "resolution": [1920, 1080], "fps": 24, "model": "agnes-video-2.5-flash", "source_size": "720P",
        "voice": "voice-02", "voice_style": "悬疑低沉、成熟男声，克制不煽情",
        "style": STYLE, "negative": NEGATIVE, "shots": shots,
        "reference_images": [
            {"id": rid, "file": f"reference/{rid}.png",
             "kind": "character" if rid[0] == "C" else "scene" if rid[0] == "S" else "prop",
             "description": REF_DESC[rid]} for rid in refs_all],
        "reference_status": {"approved_generated": refs_all, "pending": []},
        "reference_mode_supported": True,
        "provider_constraints": "Agnes 2.5 Flash mode=reference, images=[1..5 public immutable raw URLs pinned to reference/revision.txt]; no width/height/fps/negative_prompt fields.",
        "facts_checked": "见 事实核查.md",
    }
    (HERE / "story.json").write_text(json.dumps(story, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    md = [f"# 《{TITLE}》分镜提示词包\n\n三分钟横屏 · 1920×1080 · 24fps · 30镜 · 180秒\n"]
    for s in shots:
        md.append(f"## {s['id']}｜{s['start']:03d}–{s['start']+s['duration']:03d}s（{s['duration']}秒）\n\n"
                  f"- 参考图：{', '.join(s['reference_images'])}\n- 旁白：{s['narration']}\n"
                  f"- 运镜：{s['camera']}\n- 音效：{s['sfx']}\n\n```text\n{s['prompt']}\n```\n")
    (HERE / "screenplay.md").write_text("\n".join(md), encoding="utf-8")
    print(f"Built {len(shots)} shots / 180s; {len(refs_all)} references declared; approvals in ledger: {len(approvals)}.")
    return story


if __name__ == "__main__":
    build()
