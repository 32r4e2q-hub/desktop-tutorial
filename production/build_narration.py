def parse_scenes(path: Path):
    lines = path.read_text(encoding="utf-8-sig").splitlines()
    header = next(i for i, ln in enumerate(lines) if ln.startswith("Scene Number,"))
    return [(float(r["Start Time (seconds)"]), float(r["End Time (seconds)"]))
            for r in csv.DictReader(lines[header:])]


def est_audio(text: str) -> float:
    chars = sum(1 for ch in text if "\u3400" <= ch <= "\u9fff" or ch.isalnum())
    return chars / CHARS_PER_SEC + TAIL_PAUSE


def build():
    scenes = parse_scenes(SCENES)
    payload = []
    cursor = -999.0
    n_cues = 0
    est_total = 0.0
    for title, cues in SECTIONS:
        section = {"title": title, "cues": []}
        for t0, text in cues:
            target = min(max(est_audio(text) * VIA, MIN_SPAN), MAX_SPAN)
            floor = cursor + GAP
            # scene that best covers t0 but starts after floor
            best = None
            for i, (s, e) in enumerate(scenes):
                if e <= floor + 0.5:
                    continue
                d = abs((s + e) / 2 - max(t0, floor))
                if best is None or d < best[0]:
                    best = (d, i)
                if s >= t0:
                    break
            if best is None:
                raise RuntimeError("source exhausted")
            idx = best[1]
            a = max(scenes[idx][0], floor)
            if a >= scenes[idx][1] - 0.8:
                idx += 1
                if idx >= len(scenes):
                    raise RuntimeError("ran out of scenes")
                a = scenes[idx][0]
            end = scenes[idx][1]
            j = idx
            while end - a < target and j + 1 < len(scenes):
                j += 1
                end = min(scenes[j][1], a + MAX_SPAN)
            end = min(end, a + max(target, MIN_SPAN) * 1.12, DURATION_CAP)
            if end - a < MIN_SPAN - 0.01:
                end = min(a + max(target * 1.12, MIN_SPAN), DURATION_CAP)
            if end - a < MIN_SPAN - 0.01:
                end = min(a + MIN_SPAN, DURATION_CAP)
            section["cues"].append({
                "text": text,
                "clips": [[round(a, 3), round(end, 3)]],
                "clip_texts": [text],
            })
            est_total += est_audio(text) + 0.1
            n_cues += 1
            cursor = end
        payload.append(section)
    OUT.write_text(json.dumps(payload, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"WROTE {OUT}: sections={len(payload)} cues={n_cues} est={est_total:.1f}s ({est_total/60:.2f}min)")


if __name__ == "__main__":
    build()
